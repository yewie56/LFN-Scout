from pathlib import Path
checks=[]
def ck(name, cond): checks.append((name, bool(cond)))
root=Path('.')
gradle=(root/'app/build.gradle.kts').read_text()
station=(root/'app/src/main/java/de/brummbeobachter/app/SeismicStationPolicy.kt').read_text()
amp=(root/'app/src/main/java/de/brummbeobachter/app/SeismicAmplitudePolicy.kt').read_text()
reg=(root/'app/src/main/java/de/brummbeobachter/app/SeismicRegionalPolicy.kt').read_text()
svc=(root/'app/src/main/java/de/brummbeobachter/app/SeismicLiveService.kt').read_text()
ui=(root/'app/src/main/java/de/brummbeobachter/app/MainActivity.kt').read_text()
ch=(root/'CHANGELOG.md').read_text()
ck('versionName 0.4.69', 'versionName = "0.4.69"' in gradle)
ck('versionCode 109', 'versionCode = 109' in gradle)
ck('FDSN sensitivity parsed', 'sensitivityFrequencyHz' in station and 'sensitivityUnits' in station)
ck('M/S to nm/s policy', '1.0e9 / sensitivity' in amp)
ck('WBBU reference 40000', 'WBBU_REFERENCE_SCALE_NM_PER_SEC = 40000.0' in amp)
ck('WBBU row ratio 4.95', 'WBBU_REFERENCE_ROW_SPACINGS = 4.95' in amp)
ck('helicorder supports valueScale', 'valueScale: Double?' in reg)
ck('calibration success log', 'SEISMIC_CALIBRATION_OK' in svc)
ck('calibration fallback log', 'SEISMIC_CALIBRATION_FALLBACK' in svc)
ck('fixed WBBU UI scale', 'fixedNmPerSecPerRow' in ui)
ck('WBBU dimension bar', 'WBBU_REFERENCE_ROW_SPACINGS' in ui and 'barHeight' in ui)
ck('physical unit UI', 'amplitudeUnit == "nm/s"' in ui)
ck('response caveat UI', 'keine vollständige frequenzabhängige Response-Deconvolution' in ui)
ck('48 half-hour plot retained', 'ROW_COUNT = 48' in reg and 'ROW_MINUTES = 30' in reg)
ck('amplitude selftest exists', (root/'SeismicAmplitudeSelfTest.kt').exists())
ck('changelog', 'v0.4.69' in ch)
for n,ok in checks: print(('PASS' if ok else 'FAIL'), n)
print(f'{sum(ok for _,ok in checks)}/{len(checks)} PASS')
raise SystemExit(0 if all(ok for _,ok in checks) else 1)
