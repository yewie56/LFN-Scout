from pathlib import Path
checks=[]
def ck(name, cond): checks.append((name, bool(cond)))
root=Path('.')
gradle=(root/'app/build.gradle.kts').read_text()
ui=(root/'app/src/main/java/de/brummbeobachter/app/MainActivity.kt').read_text()
ch=(root/'CHANGELOG.md').read_text()
readme=(root/'README.md').read_text()
test=(root/'app/src/test/java/de/brummbeobachter/app/SeismicHelicorderComposeContractTest.kt')
ck('versionName 0.4.70', 'versionName = "0.4.70"' in gradle)
ck('versionCode 110', 'versionCode = 110' in gradle)
ck('Box import present', 'import androidx.compose.foundation.layout.Box' in ui)
ck('helicorder label uses for loop', 'for (row in data.helicorderRows)' in ui)
ck('old label forEach absent', 'data.helicorderRows.forEach { row ->' not in ui)
ck('Canvas forEachIndexed retained', 'data.helicorderRows.forEachIndexed { rowIndex, row ->' in ui)
ck('48-row plot retained', 'Klassisches 24-h-Seismogramm · 30 Minuten je Zeile' in ui)
ck('WBBU scale retained', '40000 nm/s' in ui and '4,95 Zeilenabstände' in ui)
ck('compose regression test exists', test.exists())
ck('changelog updated', 'v0.4.70' in ch and 'SeismicHelicorderComposeContractTest' in ch)
ck('readme updated', '# LFN-Scout v0.4.70' in readme)
for n,ok in checks: print(('PASS' if ok else 'FAIL'), n)
print(f'{sum(ok for _,ok in checks)}/{len(checks)} PASS')
raise SystemExit(0 if all(ok for _,ok in checks) else 1)
