from pathlib import Path
checks=[]
def ck(name, cond): checks.append((name, bool(cond)))
root=Path('.')
gradle=(root/'app/build.gradle.kts').read_text()
svc=(root/'app/src/main/java/de/brummbeobachter/app/SeismicLiveService.kt').read_text()
pol=(root/'app/src/main/java/de/brummbeobachter/app/SeismicRegionalPolicy.kt').read_text()
ui=(root/'app/src/main/java/de/brummbeobachter/app/MainActivity.kt').read_text()
ch=(root/'CHANGELOG.md').read_text()
ck('versionName 0.4.68', 'versionName = "0.4.68"' in gradle)
ck('versionCode 108', 'versionCode = 108' in gradle)
ck('WBBU coordinates', '49.62294' in pol and '8.49384' in pol)
ck('special radius 30km', 'SPECIAL_RADIUS_KM = 30.0' in pol)
ck('48 half-hour rows', 'ROW_COUNT = 48' in pol and 'ROW_MINUTES = 30' in pol)
ck('alternating color policy', 'row % 2 == 0' in pol)
ck('WBBU only today', 'specialZone && window.isToday' in svc)
ck('WBBU URL', 'HS.WBBU.png' in svc)
ck('WBBU fallback to normal path', 'if (wbbu != null) return Result.Success(wbbu)' in svc)
ck('classic plot title', '48 Zeilen' in ui and '30 Minuten je Zeile' in ui)
ck('blue trace', '0xFF1565C0' in ui)
ck('red trace', '0xFFC62828' in ui)
ck('Valencia documented general principle', 'Valencia' in ui)
ck('regression selftest exists', (root/'SeismicRegionalHelicorderSelfTest.kt').exists())
ck('changelog', 'v0.4.68' in ch)
for n,ok in checks: print(('PASS' if ok else 'FAIL'), n)
print(f'{sum(ok for _,ok in checks)}/{len(checks)} PASS')
raise SystemExit(0 if all(ok for _,ok in checks) else 1)
